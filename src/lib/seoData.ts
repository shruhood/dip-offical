import type { Service } from '../types';

export const MARKETPLACE_CANONICAL_ORIGIN = 'https://digitalindiaproject.com';
export const CORE_SEO_SERVICES_COUNT = 145;

export type SeoOgType = 'website' | 'product';
export type SeoSchemaType = 'Service' | 'Product';

export interface CatalogSeoRecord {
  id: string;
  slug: string;
  name: string;
  category: string;
  seoTitle: string;
  seoDescription: string;
  focusKeyword: string;
  secondaryKeywords: string[];
  canonicalPath: string;
  canonicalUrl: string;
  ogType: SeoOgType;
  schemaType: SeoSchemaType;
  indexable: boolean;
}

type RawSeoSeed = readonly [
  id: string,
  slug: string,
  name: string,
  category: string,
  seoTitle: string,
  seoDescription: string,
  focusKeyword: string,
  secondaryKeywords: readonly string[],
  ogType?: SeoOgType
];

function hydrateSeoRecord([
  id,
  slug,
  name,
  category,
  seoTitle,
  seoDescription,
  focusKeyword,
  secondaryKeywords,
  ogType = 'website',
]: RawSeoSeed): CatalogSeoRecord {
  const canonicalPath = `/services/${slug}`;
  return {
    id,
    slug,
    name,
    category,
    seoTitle,
    seoDescription,
    focusKeyword,
    secondaryKeywords: [...secondaryKeywords],
    canonicalPath,
    canonicalUrl: `${MARKETPLACE_CANONICAL_ORIGIN}${canonicalPath}`,
    ogType,
    schemaType: ogType === 'product' ? 'Product' : 'Service',
    indexable: true,
  };
}

