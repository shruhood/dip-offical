function buildFallbackSeoRecord(service: Partial<Service>): CatalogSeoRecord {
  const slug = String(service.slug || service.id || 'service').trim().toLowerCase();
  const id = String(service.id || slug).trim();
  const name = String(service.name || 'Digital Service').trim();
  const category = String(service.category || 'personal').trim();
  const isProduct = service.productType === 'digital_product';
  const fee = Number(service.serviceCharge || 0);
  const priceTag =
    service.pricingType === 'custom'
      ? ''
      : service.pricingType === 'free'
      ? ' (₹0 Join)'
      : fee > 0
      ? ` (₹${fee.toLocaleString('en-IN')})`
      : '';

  const rawTitle = `${name}${priceTag} | Digital India Project`;
  const seoTitle = rawTitle.length <= 120 ? rawTitle : `${name.slice(0, 88)} | Digital India Project`;
  const baseDesc = String(service.seoDescription || service.shortDesc || `${name} online assistance on Digital India Project.`).trim();
  const seoDescription =
    baseDesc.length <= 160
      ? baseDesc
      : `${baseDesc.slice(0, 157).replace(/\s+\S*$/, '')}...`;

  return {
    id,
    slug,
    name,
    category,
    seoTitle,
    seoDescription,
    focusKeyword: String(service.focusKeyword || name).toLowerCase().slice(0, 100),
    secondaryKeywords: [
      name.toLowerCase(),
      category.replace(/-/g, ' '),
      'digital india project',
    ],
    canonicalPath: `/services/${slug}`,
    canonicalUrl: `${MARKETPLACE_CANONICAL_ORIGIN}/services/${encodeURIComponent(slug)}`,
    ogType: isProduct ? 'product' : 'website',
    schemaType: isProduct ? 'Product' : 'Service',
    indexable: service.published !== false,
  };
}

/**
 * Look up canonical SEO metadata by `slug` or `id`.
 * Falls back cleanly to package SEO entries or deterministic derivation when given a custom admin service.
 */
export function getServiceSeoMetadata(
  slugOrId: string,
  fallbackService?: Partial<Service>
): CatalogSeoRecord | null {
  const key = String(slugOrId || '').trim();
  const lower = key.toLowerCase();

  const exact =
    SERVICE_SEO_BY_ID[key] ||
    SERVICE_SEO_BY_SLUG[lower] ||
    PACKAGE_SEO_BY_ID[key] ||
    PACKAGE_SEO_BY_SLUG[lower];

  if (exact) {
    return fallbackService
      ? { ...exact, indexable: fallbackService.published !== false }
      : exact;
  }

  if (fallbackService?.id) {
    const byId = SERVICE_SEO_BY_ID[fallbackService.id] || PACKAGE_SEO_BY_ID[fallbackService.id];
    if (byId) {
      return { ...byId, indexable: fallbackService.published !== false };
    }
  }

  return fallbackService ? buildFallbackSeoRecord(fallbackService) : null;
}

/**
 * Enrich a Service item with canonical `seoTitle`, `seoDescription`, and `focusKeyword`
 * from `src/lib/seoData.ts` so every catalog entry and DB write remains consistent across the marketplace.
 */
export function enrichServiceWithSeoData<T extends Partial<Service>>(
  service: T,
  options?: { preserveCustomSeo?: boolean }
): T & Pick<Service, 'seoTitle' | 'seoDescription' | 'focusKeyword'> {
  const canonical = getServiceSeoMetadata(String(service.slug || service.id || ''), service);
  if (!canonical) return service;

  const preserve = options?.preserveCustomSeo === true;
  const hasCustomTitle = Boolean(preserve && service.seoTitle && service.seoTitle.trim().length > 0);
  const hasCustomDesc = Boolean(preserve && service.seoDescription && service.seoDescription.trim().length > 0);
  const hasCustomKw = Boolean(preserve && service.focusKeyword && service.focusKeyword.trim().length > 0);

  return {
    ...service,
    seoTitle: hasCustomTitle ? service.seoTitle!.trim().slice(0, 120) : canonical.seoTitle.slice(0, 120),
    seoDescription: hasCustomDesc
      ? service.seoDescription!.trim().slice(0, 240)
      : canonical.seoDescription.slice(0, 240),
    focusKeyword: hasCustomKw
      ? service.focusKeyword!.trim().slice(0, 100)
      : canonical.focusKeyword.slice(0, 100),
  };
}
