const LANGUAGE_MAP = new Map<string, IndianLanguageDefinition>(
  SUPPORTED_INDIAN_LANGUAGES.map((l) => [l.code, l])
);

export const SCHEDULED_INDIAN_LANGUAGES = SUPPORTED_INDIAN_LANGUAGES.filter(
  (l) => l.scheduledEighth
);

export function isSupportedLangCode(code?: string | null): code is SupportedLanguageCode {
  if (!code) return false;
  return LANGUAGE_MAP.has(code.toLowerCase().trim());
}

export function resolveLanguageMeta(code?: string | null): IndianLanguageDefinition {
  if (!code) return SUPPORTED_INDIAN_LANGUAGES[0];
  return LANGUAGE_MAP.get(code.toLowerCase().trim()) || SUPPORTED_INDIAN_LANGUAGES[0];
}
