import QRCode from 'qrcode';
import jsQR from 'jsqr';
import JsBarcode from 'jsbarcode';
import { PDFDocument, PageSizes, StandardFonts, rgb } from 'pdf-lib';

export interface QrPayload {
  mode: 'text' | 'url' | 'upi' | 'whatsapp' | 'wifi' | 'vcard' | 'standee';
  text?: string;
  upiId?: string;
  payeeName?: string;
  amount?: string;
  note?: string;
  phone?: string;
  message?: string;
  ssid?: string;
  wifiPassword?: string;
  wifiSecurity?: 'WPA' | 'WEP' | 'nopass';
  fullName?: string;
  org?: string;
  email?: string;
  darkColor?: string;
  lightColor?: string;
  sizePx?: number;
}

export function buildQrString(p: QrPayload): string {
  switch (p.mode) {
    case 'upi': {
      const params = new URLSearchParams({
        pa: (p.upiId || '').trim(),
        pn: (p.payeeName || 'Merchant').trim(),
        cu: 'INR',
      });
      if (p.amount && Number(p.amount) > 0) params.set('am', Number(p.amount).toFixed(2));
      if (p.note) params.set('tn', p.note.trim());
      return `upi://pay?${params.toString()}`;
    }
    case 'whatsapp': {
      const digits = (p.phone || '').replace(/[^\d]/g, '');
      const text = p.message ? `?text=${encodeURIComponent(p.message)}` : '';
      return `https://wa.me/${digits}${text}`;
    }
    case 'wifi': {
      return `WIFI:T:${p.wifiSecurity || 'WPA'};S:${p.ssid || ''};P:${p.wifiPassword || ''};;`;
    }
    case 'vcard': {
      return [
        'BEGIN:VCARD',
        'VERSION:3.0',
        `FN:${p.fullName || ''}`,
        p.org ? `ORG:${p.org}` : '',
        p.phone ? `TEL:${p.phone}` : '',
        p.email ? `EMAIL:${p.email}` : '',
        'END:VCARD',
      ]
        .filter(Boolean)
        .join('\n');
    }
    default:
      return p.text || 'https://ibakeweb.in';
  }
}

export async function generateQrCodeAssets(payload: QrPayload): Promise<{
  dataUrl: string;
  svgString: string;
  encodedText: string;
  pdfBlob: Blob;
}> {
  const encodedText = buildQrString(payload);
  const width = payload.sizePx || 512;
  const dark = payload.darkColor || '#252525';
  const light = payload.lightColor || '#FFFFFF';

  const dataUrl = await QRCode.toDataURL(encodedText, {
    width,
    margin: 2,
    color: { dark, light },
    errorCorrectionLevel: 'M',
  });

  const svgString = await QRCode.toString(encodedText, {
    type: 'svg',
    margin: 2,
    color: { dark, light },
  });

  // Generate printable A5/A4 QR Standee PDF
  const pdf = await PDFDocument.create();
  const [w, h] = PageSizes.A4;
  const page = pdf.addPage([w, h]);
  const font = await pdf.embedFont(StandardFonts.HelveticaBold);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);

  const pngBytes = await fetch(dataUrl).then((r) => r.arrayBuffer());
  const embeddedQr = await pdf.embedPng(pngBytes);

  const title =
    payload.mode === 'upi'
      ? `Scan & Pay via UPI`
      : payload.payeeName || payload.fullName || 'Scan QR Code';
  const subtitle =
    payload.mode === 'upi'
      ? `${payload.payeeName || ''} (${payload.upiId || ''})`
      : encodedText.slice(0, 72);

  page.drawText(title.replace(/[^\x20-\x7E]/g, ' '), {
    x: 64,
    y: h - 90,
    size: 24,
    font,
    color: rgb(0.14, 0.14, 0.14),
  });
  page.drawText(subtitle.replace(/[^\x20-\x7E]/g, ' '), {
    x: 64,
    y: h - 120,
    size: 13,
    font: regular,
    color: rgb(0.4, 0.4, 0.4),
  });
  page.drawImage(embeddedQr, {
    x: (w - 300) / 2,
    y: h - 460,
    width: 300,
    height: 300,
  });
  page.drawText('Generated by Digital Tools Tray (BakeWeb · DIGITAL INDIA PROJECT)', {
    x: 64,
    y: 48,
    size: 10,
    font: regular,
    color: rgb(0.5, 0.5, 0.5),
  });

  const pdfBytes = await pdf.save();
  const pdfBlob = new Blob([new Uint8Array(pdfBytes)], { type: 'application/pdf' });

  return { dataUrl, svgString, encodedText, pdfBlob };
}

export async function decodeQrFromImage(file: File): Promise<string[]> {
  const bitmap = await createImageBitmap(file);
  const canvas = document.createElement('canvas');
  canvas.width = bitmap.width;
  canvas.height = bitmap.height;
  const ctx = canvas.getContext('2d')!;
  ctx.drawImage(bitmap, 0, 0);
  bitmap.close();

  const results: string[] = [];
  const imgData = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const qr = jsQR(imgData.data, imgData.width, imgData.height);
  if (qr?.data) results.push(qr.data);

  // Also check browser BarcodeDetector if available (for 1D barcodes & multi-code images)
  if ('BarcodeDetector' in window) {
    try {
      const Detector = (window as unknown as { BarcodeDetector: new () => { detect: (src: HTMLCanvasElement) => Promise<Array<{ rawValue: string }>> } }).BarcodeDetector;
      const detector = new Detector();
      const detected = await detector.detect(canvas);
      for (const item of detected) {
        if (item.rawValue && !results.includes(item.rawValue)) {
          results.push(item.rawValue);
        }
      }
    } catch {
      // BarcodeDetector optional
    }
  }

  return results;
}

export function generateBarcodeDataUrl(
  value: string,
  format: 'CODE128' | 'EAN13' | 'CODE39' | 'UPC' = 'CODE128'
): { pngDataUrl: string; svgString: string } {
  const canvas = document.createElement('canvas');
  JsBarcode(canvas, value, {
    format,
    lineColor: '#252525',
    background: '#FFFFFF',
    width: 2,
    height: 90,
    displayValue: true,
    margin: 12,
  });

  const svgEl = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  JsBarcode(svgEl, value, {
    format,
    lineColor: '#252525',
    background: '#FFFFFF',
    width: 2,
    height: 90,
    displayValue: true,
    margin: 12,
  });

  return {
    pngDataUrl: canvas.toDataURL('image/png'),
    svgString: new XMLSerializer().serializeToString(svgEl),
  };
}
